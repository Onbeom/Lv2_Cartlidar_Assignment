"""Code128(B) 바코드 그림 만들기 — 가상 월드 바코드 질감용 (외부 라이브러리 없이 표준 패턴 표로).

패턴: 값마다 막대 · 빈칸 너비(모듈 수) 6개(정지 기호는 7개). 시작 B = 104, 검사 값 = (104 + Σ i·값) mod 103.
"""
import numpy as np

PATTERNS = [
    "212222", "222122", "222221", "121223", "121322", "131222", "122213", "122312", "132212", "221213",
    "221312", "231212", "112232", "122132", "122231", "113222", "123122", "123221", "223211", "221132",
    "221231", "213212", "223112", "312131", "311222", "321122", "321221", "312212", "322112", "322211",
    "212123", "212321", "232121", "111323", "131123", "131321", "112313", "132113", "132311", "211313",
    "231113", "231311", "112133", "112331", "132131", "113123", "113321", "133121", "313121", "211331",
    "231131", "213113", "213311", "213131", "311123", "311321", "331121", "312113", "312311", "332111",
    "314111", "221411", "431111", "111224", "111422", "121124", "121421", "141122", "141221", "112214",
    "112412", "122114", "122411", "142112", "142211", "241211", "221114", "413111", "241112", "134111",
    "111242", "121142", "121241", "114212", "124112", "124211", "411212", "421112", "421211", "212141",
    "214121", "412121", "111143", "111341", "131141", "114113", "114311", "411113", "411311", "113141",
    "114131", "311141", "411131", "211412", "211214", "211232", "2331112",
]
START_B, STOP = 104, 106
assert len(PATTERNS) == 107 and len(set(PATTERNS)) == 107
assert all(sum(map(int, p)) == 11 for p in PATTERNS[:106]) and sum(map(int, PATTERNS[STOP])) == 13


def values(text):
    v = [START_B] + [ord(ch) - 32 for ch in text]
    if any(not 0 <= x < 95 for x in v[1:]):
        raise ValueError("Code128 B 범위 밖 글자")
    check = (v[0] + sum(i * x for i, x in enumerate(v[1:], 1))) % 103
    return v + [check, STOP]


def modules(text, quiet=10):
    """막대 = 1, 빈칸 = 0 인 모듈 열 (앞뒤 조용한 영역 quiet 모듈 포함)."""
    out = [0] * quiet
    for x in values(text):
        for k, w in enumerate(PATTERNS[x]):
            out += [1 - k % 2] * int(w)
    return np.array(out + [0] * quiet, np.uint8)


def image(text, px_per_module=8, height_px=None, quiet=10):
    """흰 바탕 검은 막대 그림 (uint8, 255 = 흰색)."""
    m = modules(text, quiet)
    h = height_px or 40 * px_per_module
    row = np.repeat(np.where(m == 1, 0, 255).astype(np.uint8), px_per_module)
    return np.tile(row, (h, 1))
